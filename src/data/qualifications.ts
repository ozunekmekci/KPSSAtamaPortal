export const QUALIFICATIONS_BY_CODE: Record<string, QualificationCode> = Object.fromEntries(
  QUALIFICATION_CODES.map((item) => [item.kod, item])
);

export function getQualificationByCode(code: string): QualificationCode | undefined {
  return QUALIFICATIONS_BY_CODE[code];
}

export function isSpecialConditionCode(code: string): boolean {
  const item = QUALIFICATIONS_BY_CODE[code];
  if (item) return item.isSpecialCondition;
  // Fallback heuristic: 1xxx, 6xxx, 7xxx are special conditions
  const first = code.charAt(0);
  return first === '1' || first === '6' || first === '7';
}
