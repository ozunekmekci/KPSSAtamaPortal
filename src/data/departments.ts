export const DEPARTMENTS_BY_ID: Record<string, Department> = Object.fromEntries(
  DEPARTMENTS.map((d) => [d.id, d])
);

export const DEPARTMENTS_BY_CODE: Record<string, Department[]> = DEPARTMENTS.reduce(
  (acc, dept) => {
    // Primary code
    if (!acc[dept.nitelikKodu]) acc[dept.nitelikKodu] = [];
    if (!acc[dept.nitelikKodu].includes(dept)) {
      acc[dept.nitelikKodu].push(dept);
    }
    // Equivalent codes
    for (const es of dept.esdegerKodlar) {
      if (!acc[es]) acc[es] = [];
      if (!acc[es].includes(dept)) {
        acc[es].push(dept);
      }
    }
    return acc;
  },
  {} as Record<string, Department[]>
);

export function getDepartmentById(id: string): Department | undefined {
  return DEPARTMENTS_BY_ID[id];
}

export function getDepartmentsByCode(code: string): Department[] {
  return DEPARTMENTS_BY_CODE[code] || [];
}
